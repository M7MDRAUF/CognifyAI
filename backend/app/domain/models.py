class LLMCall(Base):
    """One provider HTTP attempt -- the billed unit (M-7, L-12, C-12).

    Not one row per agent and not one per logical completion. An agent invocation may spend three
    repair rungs and each rung up to three retries, so one step can write nine of these; `rung`
    and `attempt` together say which one a row is.

    Written on **every** terminal path. `token_usage_estimate` on `query_runs` had a single
    writer on the success path, so failed, cancelled and deadline-stopped runs recorded NULL and
    read as free.
    """

    __tablename__ = "llm_calls"
    __table_args__ = (Index("ix_llm_calls_query_run_id_created_at", "query_run_id", "created_at"),)

    id: Mapped[uuid.UUID] = mapped_column(Uuid(), primary_key=True)
    query_run_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(), ForeignKey("query_runs.id", ondelete="CASCADE")
    )
    # The component that caused the attempt. Text, not `AgentName`: the reranker and the provider
    # adapter are call sites and are not members of that enum (ADR-001).
    component: Mapped[str] = mapped_column(Text())
    provider: Mapped[str] = mapped_column(Text())
    model: Mapped[str] = mapped_column(Text())
    rung: Mapped[int] = mapped_column(Integer())
    attempt: Mapped[int] = mapped_column(Integer())
    # "success" | "failure" | "charged_failure". The third is a 2xx the vendor billed whose body
    # carried no usable answer; collapsing it into "failure" is how that usage was discarded.
    outcome: Mapped[str] = mapped_column(Text())
    failure_kind: Mapped[str | None] = mapped_column(Text(), default=None)
    # NULL = the vendor reported no usage. 0 = it reported zero. A metering row that cannot tell
    # those apart cannot be reconciled against an invoice.
    prompt_tokens: Mapped[int | None] = mapped_column(Integer(), default=None)
    completion_tokens: Mapped[int | None] = mapped_column(Integer(), default=None)
    # The call details (migration 0014; PLV8-T02, PLV-D-027), NULL when not reported: the cached
    # prompt tokens and the reasoning tokens, summed over the step's rungs; the thinking mode and
    # effort sent; the provider's id of each rung's response, in order, space-separated; and the
    # model and system fingerprint the last response named.
    cached_prompt_tokens: Mapped[int | None] = mapped_column(Integer(), default=None)
    reasoning_tokens: Mapped[int | None] = mapped_column(Integer(), default=None)
    thinking: Mapped[str | None] = mapped_column(Text(), default=None)
    reasoning_effort: Mapped[str | None] = mapped_column(Text(), default=None)
    provider_request_ids: Mapped[str | None] = mapped_column(Text(), default=None)
    response_model: Mapped[str | None] = mapped_column(Text(), default=None)
    system_fingerprint: Mapped[str | None] = mapped_column(Text(), default=None)
    latency_ms: Mapped[int] = mapped_column(Integer(), default=0)
    backoff_ms: Mapped[int] = mapped_column(Integer(), default=0)
    # NULL = unpriced. Never 0.0 for a missing rate -- a free-looking attempt never trips a
    # budget, which is the one error ADR-004 exists to prevent.
    cost_usd: Mapped[Decimal | None] = mapped_column(Numeric(12, 6), default=None)
    pricing_status: Mapped[str] = mapped_column(Text(), default="unpriced")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))


