class AgentEvent(Base):
    __tablename__ = "agent_events"
    __table_args__ = (Index("ix_agent_events_query_run_id_seq", "query_run_id", "seq"),)

    id: Mapped[uuid.UUID] = mapped_column(Uuid(), primary_key=True)
    # Monotonic emission order: created_at can collide at microsecond resolution,
    # so SSE replay and "last event" ordering rely on this database sequence.
    seq: Mapped[int] = mapped_column(BigInteger(), Identity())
    query_run_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(), ForeignKey("query_runs.id", ondelete="CASCADE")
    )
    event_type: Mapped[EventType] = mapped_column(_enum_column(EventType, "event_type"))
    agent_name: Mapped[AgentName | None] = mapped_column(
        _enum_column(AgentName, "agent_name"), default=None
    )
    # Producer identity for the events that have no agent (SDD 8.3.1). `Text` and not an enum,
    # and deliberately NOT a member of `AgentName`: the client parses `agent_name` against a
    # strict Zod enum, so a non-member value there fails the parse and the frame is dropped.
    # NULL on rows emitted before this column existed -- never inferred from `event_type`.
    component: Mapped[str | None] = mapped_column(Text(), default=None)
    message: Mapped[str] = mapped_column(Text(), default="")
    payload: Mapped[dict[str, object]] = mapped_column(JSONB(), default=dict)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
